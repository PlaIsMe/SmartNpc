"""Regenerate the human-readable index from actual reviewed examples."""
from collections import Counter, defaultdict
import json
import argparse
import tomllib
from validate_dataset import ROOT, LANGUAGES, rows


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--language", choices=LANGUAGES, default="en_us")
    args = parser.parse_args()
    language = args.language
    source = tomllib.loads((ROOT / f"data/my_chats_{language}.toml").read_text(encoding="utf-8"))
    training_blocks = [row for row in source["chat"] if row["split"] == "train"]
    reply_counts = [len(row["npc"]) if isinstance(row["npc"], list) else 1 for row in training_blocks]
    scenarios = defaultdict(list)
    files = [ROOT / f"data/clean/my_chats_{language}.jsonl"]
    for file in files:
        for row in rows(file):
            scenarios[row["scenario_id"]].append((file.name, row))
    membership = {row["scenario_id"]: split for split in ("train", "validation", "test") for row in rows(ROOT / f"data/{split}_{language}.jsonl")}
    lines = ["# All training scenarios", "", "Generated from the active prepared source. Regenerate with `python scripts/import_my_chats.py`.", "",
             f"`data/my_chats_{language}.toml` is the single editable source for all dialogue, event and witness rows. Archived starter/event files are not appended by the v2 pipeline. The model must still be trained afterward.", "",
             "Scenario IDs group examples for splitting; players never need to type these IDs. Similar wording can generalize, and replies are generated dynamically. Exact text, factual accuracy and language quality are not guaranteed by a tiny model. Try unseen paraphrases in evaluation.", "",
             "Translations/paraphrases of the same situation stay in the same split. This prevents a translated copy of a test answer leaking into training.", "",
             "| Scenario | Examples | Split | Action labels | Example input/event |", "|---|---:|---|---|---|"]
    for name, entries in sorted(scenarios.items()):
        context = json.loads(entries[0][1]["messages"][1]["content"])
        sample = context.get("speaker", {}).get("message") or "World event: " + context.get("event", {}).get("type", "unknown")
        sample = sample.replace("|", "\\|").replace("\n", " ")[:90]
        actions = sorted({json.loads(row["messages"][2]["content"])["action"]["type"] for _, row in entries})
        lines.append(f"| `{name}` | {len(entries)} | {membership.get(name, 'unknown')} | {', '.join(actions)} | {sample} |")
    lines += ["", f"Total: **{sum(len(entries) for entries in scenarios.values())} examples / {len(scenarios)} scenarios**.", "",
              "Event examples are edited in the language-specific TOML; resource-file changes are not automatically imported.", "",
              f"This dataset uses {language}. All NPCs use the selected model language; there are no per-NPC language interests.", "",
              "Witnessed-death scenarios include unknown killer/shock, a visible attributed killer, and multiple observed kills. The server, not the model, requests the existing bounded avoidance goal. Only visible nearby deaths count, and paths may fail. Speech remains action NONE.", "",
              "Event examples teach dialogue style only. Importing a line does not implement a new event trigger or action. No item is granted by a training label without server authorization.", ""]
    (ROOT / f"SCENARIOS_{language}.md").write_text("\n".join(lines), encoding="utf-8")
    usage = ["# Active training data", "", "Generated by import_my_chats.py/list_scenarios.py; counts describe prepared data, not trained weights.", "",
             f"Edit [data/my_chats_{language}.toml](data/my_chats_{language}.toml), then run `python scripts/import_my_chats.py --language {language}`.", "",
             "Every block shows `split`. Only train rows update model weights. Validation measures training; frozen test rows are read-only mirrors and are never trained.", "",
             "An `npc` reply list expands to one example per alternative with shared context/action/emotion. Counts below include every alternative; they are not TOML block counts.", "",
             f"Training source: **{len(training_blocks)} blocks**, with **{min(reply_counts, default=0)} replies minimum per block**. Alternative replies share situations; they are not independent evaluation cases.", "",
             "| Split | Examples | With conversation history |", "|---|---:|---:|"]
    action_counts = {}
    for split in ("train", "validation", "test"):
        entries = rows(ROOT / f"data/{split}_{language}.jsonl")
        usage.append(f"| {split} | {len(entries)} | {sum(bool(json.loads(row['messages'][1]['content']).get('recent_turns')) for row in entries)} |")
        action_counts[split] = Counter(json.loads(row["messages"][2]["content"])["action"]["type"] for row in entries)
    usage += ["", "| Action | Train | Validation | Frozen test |", "|---|---:|---:|---:|"]
    for action in sorted(set().union(*(set(counts) for counts in action_counts.values()))):
        usage.append(f"| {action} | {action_counts['train'][action]} | {action_counts['validation'][action]} | {action_counts['test'][action]} |")
    usage += ["", "All currently offered action types have training labels. START_NPC_CONVERSATION is reserved and not offered as a model action. Attack/retaliation, teleportation, unrestricted building and trading remain unsupported.", "",
              f"`data/clean/my_chats_{language}.jsonl`, `data/train_{language}.jsonl` and `data/validation_{language}.jsonl` are generated outputs. Starter/event/witness archives are historical sources and are not appended.", "",
              ("The eight original English frozen examples remain byte-identical." if language == "en_us" else f"The eight {LANGUAGES[language]} frozen examples are a separate localized evaluation version; they are not an independently verified quality benchmark.") + " Their visible TOML mirrors cannot be edited into training. A larger evaluation set is still needed for dialogue-quality claims.", ""]
    (ROOT / f"DATA_USAGE_{language}.md").write_text("\n".join(usage), encoding="utf-8")
    print(f"Indexed {len(scenarios)} scenarios")


if __name__ == "__main__":
    main()
